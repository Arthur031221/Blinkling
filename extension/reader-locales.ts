export type ReaderLocale = keyof typeof readerLocales;
export type ReaderStrings = (typeof readerLocales)[ReaderLocale];
export function formatReaderText(
  template: string,
  values: Record<string, string | number> = {},
): string {
  return template.replace(/\{([a-z]+)\}/g, (_, key: string) =>
    String(values[key] ?? `{${key}}`),
  );
}
