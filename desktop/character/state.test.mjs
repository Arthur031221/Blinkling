import test from "node:test";
import assert from "node:assert/strict";
import { BlinkState } from "./state.mjs";
test("typing renews the quiet deadline without permanently pinning a focused chat", () => {
  const s = new BlinkState();
  s.openChat();
  s.hover(false, 0);
  s.activity(1000);
  s.tick(2000);
  assert.equal(s.chatOpen, true);
  s.tick(2500);
  assert.equal(s.chatOpen, false);
  assert.equal(s.mode, "peek");
});
test("hover reveals immediately; retreat waits 1500ms and can be cancelled by a menu hover", () => {
  const s = new BlinkState();
  s.hover(true, 100);
  assert.equal(s.mode, "hover");
  s.hover(false, 200);
  s.tick(1699);
  assert.equal(s.mode, "hover");
  s.hover(true, 1700);
  s.tick(3000);
  assert.equal(s.mode, "hover");
  s.hover(false, 3000);
  s.tick(4500);
  assert.equal(s.mode, "peek");
});
test("pin defaults off; pinned chat survives leaving, unpin returns after quiet moment", () => {
  const s = new BlinkState();
  assert.equal(s.pinned, false);
  s.openChat();
  s.pin(true);
  s.hover(false, 0);
  s.tick(5000);
  assert.equal(s.chatOpen, true);
  s.pin(false);
  s.hover(false, 5000);
  s.tick(6500);
  assert.equal(s.chatOpen, false);
  assert.equal(s.mode, "peek");
});
test("drag never collapses while held; release bounces before retreat", () => {
  const s = new BlinkState();
  s.startDrag();
  s.hover(false, 0);
  s.tick(5000);
  assert.equal(s.mode, "drag");
  s.drop(5100);
  assert.equal(s.mode, "drop");
  s.tick(5600);
  assert.equal(s.mode, "hover");
  s.tick(7100);
  assert.equal(s.mode, "peek");
});
